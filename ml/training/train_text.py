"""Train the report text classifier and write the model plus its evaluation.

Run from the repo root:  python ml/training/train_text.py
"""

import argparse
import csv
import json
from datetime import date
from pathlib import Path

import joblib
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    precision_recall_fscore_support,
)
from sklearn.pipeline import FeatureUnion, Pipeline

SEED = 42
ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = ROOT / "ml" / "datasets"
MODEL_PATH = ROOT / "ml" / "models" / "text_classifier.joblib"
REPORT_DIR = ROOT / "ml" / "reports"
THRESHOLDS = [0.3, 0.4, 0.5, 0.6, 0.7]


def read_rows(name):
    with open(DATA_DIR / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def load_data():
    train = read_rows("civic_text_v2.csv")
    test = read_rows("civic_text_v1.csv")

    # the generated file repeats sentences, and a test text must never be trained on
    banned = {r["text"].strip().lower() for r in test}
    seen = set()
    kept = []
    for r in train:
        key = r["text"].strip().lower()
        if key in banned or key in seen:
            continue
        seen.add(key)
        kept.append(r)
    return kept, test


def build_pipeline(c_value):
    features = FeatureUnion(
        [
            (
                "words",
                TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True, lowercase=True),
            ),
            (
                "chars",
                TfidfVectorizer(
                    analyzer="char_wb",
                    ngram_range=(2, 4),
                    sublinear_tf=True,
                    lowercase=True,
                ),
            ),
        ]
    )
    clf = LogisticRegression(
        C=c_value, max_iter=2000, class_weight="balanced", random_state=SEED
    )
    return Pipeline([("features", features), ("clf", clf)])


def evaluate(model, test, labels):
    texts = [r["text"] for r in test]
    truth = [r["category"] for r in test]
    probs = model.predict_proba(texts)
    classes = list(model.classes_)
    pred = [classes[i] for i in probs.argmax(axis=1)]
    top = probs.max(axis=1)

    prec, rec, f1, support = precision_recall_fscore_support(
        truth, pred, labels=labels, zero_division=0
    )
    per_class = {
        lab: {
            "precision": round(float(prec[i]), 3),
            "recall": round(float(rec[i]), 3),
            "f1": round(float(f1[i]), 3),
            "support": int(support[i]),
        }
        for i, lab in enumerate(labels)
    }

    by_threshold = []
    for t in THRESHOLDS:
        sure = top >= t
        sure_acc = (
            accuracy_score(np.array(truth)[sure], np.array(pred)[sure])
            if sure.any()
            else 0.0
        )
        by_threshold.append(
            {
                "threshold": t,
                "share_kept": round(float(sure.mean()), 3),
                "accuracy_on_kept": round(float(sure_acc), 3),
            }
        )

    wrong = [
        {
            "text": texts[i],
            "true": truth[i],
            "predicted": pred[i],
            "confidence": round(float(top[i]), 3),
        }
        for i in range(len(texts))
        if truth[i] != pred[i]
    ]
    return {
        "accuracy": round(float(accuracy_score(truth, pred)), 3),
        "test_rows": len(test),
        "labels": labels,
        "per_class": per_class,
        "confusion_matrix": confusion_matrix(truth, pred, labels=labels).tolist(),
        "by_threshold": by_threshold,
        "mistakes": wrong,
    }


def write_report(result, info):
    labels = result["labels"]
    lines = [
        "# Text classifier evaluation",
        "",
        f"Generated by `ml/training/train_text.py` on {info['date']}. Seed {SEED}.",
        "",
        f"- Training rows: {info['train_rows']} (`civic_text_v2.csv`, de-duplicated)",
        f"- Test rows: {result['test_rows']} (all of `civic_text_v1.csv`, handwritten and never trained on)",
        f"- Model: TF-IDF (word 1-2 grams + character 2-4 grams) into Logistic Regression, C={info['c']}",
        f"- Accuracy: {result['accuracy']}",
        "",
        "## Per class",
        "",
        "| Category | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ]
    for lab in labels:
        m = result["per_class"][lab]
        lines.append(
            f"| {lab} | {m['precision']} | {m['recall']} | {m['f1']} | {m['support']} |"
        )

    lines += [
        "",
        "## Confusion matrix",
        "",
        "Rows are the true category, columns the predicted one.",
        "",
    ]
    lines.append("| true \\ predicted | " + " | ".join(labels) + " |")
    lines.append("|---" * (len(labels) + 1) + "|")
    for lab, row in zip(labels, result["confusion_matrix"]):
        lines.append(f"| {lab} | " + " | ".join(str(v) for v in row) + " |")

    lines += [
        "",
        "## Confidence threshold",
        "",
        "Share of hold-out texts the model would answer on its own at each threshold, and how accurate those answers are. The rest go to manual review.",
        "",
        "| Threshold | Share kept | Accuracy on kept |",
        "|---|---|---|",
    ]
    for row in result["by_threshold"]:
        lines.append(
            f"| {row['threshold']} | {row['share_kept']} | {row['accuracy_on_kept']} |"
        )

    lines += ["", "## Mistakes", ""]
    if result["mistakes"]:
        lines += ["| Text | True | Predicted | Confidence |", "|---|---|---|---|"]
        for m in result["mistakes"]:
            text = m["text"].replace("|", "/")
            lines.append(
                f"| {text} | {m['true']} | {m['predicted']} | {m['confidence']} |"
            )
    else:
        lines.append("None.")

    lines += ["", "Weaknesses are written up in `docs/text_classifier.md`.", ""]
    (REPORT_DIR / "text_classifier.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--c", type=float, default=10.0, help="inverse regularisation strength"
    )
    args = parser.parse_args()

    taxonomy = json.loads((ROOT / "shared" / "categories.json").read_text())
    labels = [c["key"] for c in taxonomy["categories"]]

    train, test = load_data()
    unknown = {r["category"] for r in train + test} - set(labels)
    if unknown:
        raise SystemExit(f"categories not in taxonomy: {sorted(unknown)}")

    model = build_pipeline(args.c)
    model.fit([r["text"] for r in train], [r["category"] for r in train])

    result = evaluate(model, test, labels)
    info = {
        "date": date.today().isoformat(),
        "train_rows": len(train),
        "c": args.c,
    }

    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, MODEL_PATH)
    (REPORT_DIR / "text_classifier.json").write_text(
        json.dumps(result, indent=1), encoding="utf-8"
    )
    write_report(result, info)
    print(
        f"accuracy {result['accuracy']} on {result['test_rows']} rows, {len(train)} training rows"
    )


if __name__ == "__main__":
    main()
